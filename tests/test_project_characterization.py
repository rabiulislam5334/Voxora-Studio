@pytest.mark.parametrize("name", GOLDEN)
def test_golden_fixture_roundtrips_exactly_through_the_serializer(name):
    raw = _load_raw(name)
    assert project_to_dict(project_from_dict(raw)) == raw


@pytest.mark.parametrize("name", GOLDEN)
def test_golden_fixture_survives_open_save_reopen_without_losing_data(name, tmp_path):
    manager, project = _open(FIXTURES / name)
    before = project_to_dict(project)

    saved = manager.save(tmp_path / "copy.voxora")
    saved_raw = json.loads(saved.read_text(encoding="utf-8"))

    # save() touches updated_at; everything else must be identical
    assert saved_raw.pop("updated_at") >= before["updated_at"]
    expected = dict(before)
    expected.pop("updated_at")
    assert saved_raw == expected

    _, reopened = _open(saved)
    again = project_to_dict(reopened)
    again.pop("updated_at")
    assert again == expected


