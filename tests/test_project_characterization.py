"""Phase 1 / Step 1 -- characterization tests for project persistence.

Pins down how ProjectManager / the serializer behave TODAY, using golden
schema-v1 fixtures that were generated by the unmodified serializer
(tests/fixtures/v1/). They must keep passing through every Phase 1 step:
the whole point of the schema-v2 migration is that these files still open
and lose nothing.

Conventions
-----------
* Plain tests describe behaviour that must be preserved.
* ``test_current_...`` documents accepted-for-now behaviour that a later
  step changes ON PURPOSE (update it in that commit and say why).
* ``@pytest.mark.xfail(strict=True)`` marks a verified defect. The test asserts
  the DESIRED behaviour; it currently fails (reported as "xfailed"). When the
  defect is fixed the test starts passing, strict mode turns that into a
  failure, and you simply delete the marker.
"""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from app.core.exceptions import ProjectError
from app.projects.manager import PROJECT_EXTENSION, ProjectManager
from app.projects.serializer import CURRENT_SCHEMA_VERSION, project_from_dict, project_to_dict
from app.studio.models import StudioState

FIXTURES = Path(__file__).parent / "fixtures" / "v1"
GOLDEN = ["v1_minimal.voxora", "v1_full.voxora"]


def _load_raw(name: str) -> dict:
    return json.loads((FIXTURES / name).read_text(encoding="utf-8"))


def _write_json(path: Path, data) -> Path:
    path.write_text(json.dumps(data), encoding="utf-8")
    return path


def _open(path: Path):
    manager = ProjectManager()
    project = manager.open(path)
    return manager, project


