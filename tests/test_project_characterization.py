def test_failed_replace_keeps_original_file_and_manager_state(tmp_path, monkeypatch):
    manager = ProjectManager()
    manager.new_project("Original")
    target = manager.save(tmp_path / "keep.voxora")
    original_bytes = target.read_bytes()

    manager.current_project.name = "Changed"
    manager.mark_dirty()

    original_replace = Path.replace

    def boom(self, destination):
        # Fail only the replace of the project file itself; the rolling backup
        # (written to the default backups dir) must still succeed.
        if Path(destination) != target:
            return original_replace(self, destination)
        raise OSError("simulated disk failure")

    monkeypatch.setattr(Path, "replace", boom)
    with pytest.raises(ProjectError, match="Could not save"):
        manager.save()
    monkeypatch.undo()

    assert target.read_bytes() == original_bytes                      # original untouched
    assert sorted(p.name for p in tmp_path.iterdir()) == ["keep.voxora"]  # temp file cleaned up
    assert manager.dirty is True and manager.current_path == target   # still unsaved, still bound


def test_current_unserializable_settings_raise_typeerror_but_leave_no_damage(tmp_path):
    # json.dump fails part-way through. Today that surfaces as a raw TypeError
    # (not ProjectError); the original file and folder must still be intact.
    manager = ProjectManager()
    target = manager.save(tmp_path / "keep.voxora")
    original_bytes = target.read_bytes()

    manager.current_project.settings["bad"] = object()
    manager.mark_dirty()
    with pytest.raises(TypeError):
        manager.save()

    assert target.read_bytes() == original_bytes
    assert sorted(p.name for p in tmp_path.iterdir()) == ["keep.voxora"]
    assert manager.dirty is True


