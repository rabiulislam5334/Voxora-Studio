"""Deterministic bridge from Voxora narration cues to Cinematic Skill Films.

This is a first vertical slice: it turns already segmented script/narration lines
into a coherent moving-board film. It does not claim semantic shot selection,
asset acquisition, forced alignment, or character animation.
"""
from __future__ import annotations

import hashlib
import json
import os
import tempfile
import textwrap
from dataclasses import dataclass
from pathlib import Path
from typing import Optional, Sequence

from PIL import Image, ImageOps


class CinematicSkillFilmBuildError(ValueError):
    """Raised when a narration-backed shot plan cannot become a valid Film."""


@dataclass(frozen=True)
class CinematicSkillShot:
    """Optional visual direction for one narration line.

    kind: card | title | counter. Coordinates are generated by the builder so
    callers cannot accidentally create an unbounded world layout.
    """

    line_id: int
    kind: str = "card"
    title: Optional[str] = None
    body: tuple[str, ...] = ()
    emphasis_word: Optional[str] = None
    counter_value: Optional[int] = None
    counter_prefix: str = ""
    counter_suffix: str = ""
    counter_caption: Optional[str] = None
    director_shot_id: Optional[str] = None
    image_path: Optional[str] = None


class CinematicSkillFilmBuilder:
    """Build an upstream Film from exact Voxora line timings and optional shot cues."""

    SUPPORTED_KINDS = frozenset({"card", "title", "counter", "image"})

    @staticmethod
    def _stage_image(narration_doc, image_path: str) -> tuple[str, float]:
        """Copy a verified local still into the temporary Film project context."""
        if not isinstance(image_path, str) or not image_path.strip():
            raise CinematicSkillFilmBuildError("image shots require a non-empty image_path")
        source = Path(image_path).expanduser()
        if source.is_symlink():
            raise CinematicSkillFilmBuildError("symbolic-link visual assets are not accepted")
        try:
            source = source.resolve(strict=True)
            if not source.is_file():
                raise CinematicSkillFilmBuildError("visual asset must be a regular file")
            if source.stat().st_size <= 0 or source.stat().st_size > 100 * 1024 * 1024:
                raise CinematicSkillFilmBuildError("visual asset is empty or exceeds the 100 MiB limit")
        except OSError as exc:
            raise CinematicSkillFilmBuildError(f"visual asset is unavailable: {exc}") from exc

        raw_project_dir = getattr(narration_doc, "dir", None)
        raw_prep_dir = getattr(narration_doc, "prep", None)
        if raw_project_dir is None or raw_prep_dir is None:
            raise CinematicSkillFilmBuildError(
                "image shots require a narration document with project dir and prep paths"
            )
        if Path(raw_project_dir).expanduser().is_symlink() or Path(raw_prep_dir).expanduser().is_symlink():
            raise CinematicSkillFilmBuildError("Cinematic Skill project paths must not be symbolic links")
        project_dir = Path(raw_project_dir).expanduser().resolve()
        prep_dir = Path(raw_prep_dir).expanduser().resolve()
        try:
            prep_dir.relative_to(project_dir)
        except ValueError:
            raise CinematicSkillFilmBuildError("Cinematic Skill asset staging must remain inside its project workspace") from None

        photos_dir = prep_dir / "photos"
        if photos_dir.is_symlink():
            raise CinematicSkillFilmBuildError("visual staging directory must not be a symbolic link")
        photos_dir.mkdir(parents=True, exist_ok=True)

        digest = hashlib.sha256()
        try:
            with source.open("rb") as stream:
                for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                    digest.update(chunk)
        except OSError as exc:
            raise CinematicSkillFilmBuildError(f"could not read visual asset: {exc}") from exc
        key = "voxora_" + digest.hexdigest()[:24]
        target = photos_dir / f"{key}.jpg"

        if target.is_symlink():
            raise CinematicSkillFilmBuildError("staged visual asset path must not be a symbolic link")
        if not target.is_file():
            temporary = None
            try:
                with Image.open(source) as original:
                    image = ImageOps.exif_transpose(original)
                    image.load()
                    if image.mode in ("RGBA", "LA", "P"):
                        rgba = image.convert("RGBA")
                        prepared = Image.new("RGB", rgba.size, (235, 228, 214))
                        prepared.paste(rgba, mask=rgba.getchannel("A"))
                    else:
                        prepared = image.convert("RGB")
                    prepared.thumbnail((2200, 2200), Image.Resampling.LANCZOS)
                    fd, temp_name = tempfile.mkstemp(prefix=".voxora-image-", suffix=".jpg", dir=str(photos_dir))
                    os.close(fd)
                    temporary = Path(temp_name)
                    prepared.save(temporary, format="JPEG", quality=93, optimize=False)
                    width, height = prepared.size
                    prepared.close()
            except (OSError, ValueError, Image.DecompressionBombError) as exc:
                if temporary is not None:
                    temporary.unlink(missing_ok=True)
                raise CinematicSkillFilmBuildError(f"visual asset is not a supported readable image: {exc}") from exc
            try:
                os.replace(temporary, target)
            finally:
                if temporary is not None:
                    temporary.unlink(missing_ok=True)
        else:
            try:
                with Image.open(target) as prepared:
                    width, height = prepared.size
            except OSError as exc:
                raise CinematicSkillFilmBuildError(f"staged visual asset is corrupt: {exc}") from exc

        metadata_path = photos_dir / "meta.json"
        if metadata_path.is_symlink():
            raise CinematicSkillFilmBuildError("visual metadata path must not be a symbolic link")
        try:
            metadata = json.loads(metadata_path.read_text(encoding="utf-8")) if metadata_path.is_file() else {}
        except (OSError, json.JSONDecodeError) as exc:
            raise CinematicSkillFilmBuildError(f"prepared visual metadata is invalid: {exc}") from exc
        if not isinstance(metadata, dict):
            raise CinematicSkillFilmBuildError("prepared visual metadata must be an object")
        metadata[key] = {"w": width, "h": height, "kind": "photo"}
        fd, temp_meta_name = tempfile.mkstemp(prefix=".voxora-meta-", suffix=".json", dir=str(photos_dir))
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as stream:
                json.dump(metadata, stream, ensure_ascii=False, sort_keys=True)
                stream.flush()
                os.fsync(stream.fileno())
            os.replace(temp_meta_name, metadata_path)
        finally:
            Path(temp_meta_name).unlink(missing_ok=True)
        narration_doc.meta = metadata
        return key, width / height

    def __init__(self, *, engine_module=None):
        # Dependency injection keeps tests and the core Voxora install independent
        # of the optional NumPy/Skia runtime.
        self._engine_module = engine_module

    def _engine(self):
        if self._engine_module is not None:
            return self._engine_module
        try:
            from app.universal.cinematic_skill import engine
        except (ImportError, OSError) as exc:
            raise CinematicSkillFilmBuildError(
                "Cinematic Skill's optional local runtime is unavailable; "
                "install requirements-cinematic-skill.txt to use this renderer"
            ) from exc
        return engine

    @staticmethod
    def _wrap_lines(text: str, *, width: int = 38, max_lines: int = 5) -> tuple[str, ...]:
        if not isinstance(text, str) or not text.strip():
            raise CinematicSkillFilmBuildError("shot body text must be non-empty")
        lines = tuple(textwrap.wrap(
            " ".join(text.split()), width=width, break_long_words=False,
            break_on_hyphens=False,
        ))
        if not lines:
            raise CinematicSkillFilmBuildError("shot body text must be non-empty")
        if len(lines) > max_lines:
            raise CinematicSkillFilmBuildError(
                f"shot body needs {len(lines)} lines; maximum is {max_lines}. "
                "Split the narration into shorter timed lines instead of dropping script text."
            )
        return lines

    def build(
        self,
        narration_doc,
        shots: Optional[Sequence[CinematicSkillShot]] = None,
        *,
        look: str = "wall",
        fps: int = 30,
    ):
        """Return an upstream Film; supplied narration timings remain authoritative.

        When shots are omitted, one clean explainer card is generated per measured
        narration line. Optional emphasis words use only exact doc.W() timestamps.
        """
        if not hasattr(narration_doc, "lines") or not hasattr(narration_doc, "duration"):
            raise CinematicSkillFilmBuildError(
                "narration_doc must expose measured lines and total duration"
            )
        if isinstance(fps, bool) or not isinstance(fps, int) or not 1 <= fps <= 60:
            raise CinematicSkillFilmBuildError("fps must be an integer from 1 to 60")

        lines = tuple(narration_doc.lines.values())
        if not lines:
            raise CinematicSkillFilmBuildError("at least one narration line is required")
        if any(line.end_seconds > narration_doc.duration for line in lines):
            raise CinematicSkillFilmBuildError("narration line exceeds the declared duration")

        if shots is None:
            shot_by_id = {}
        else:
            parsed = tuple(shots)
            if not all(isinstance(item, CinematicSkillShot) for item in parsed):
                raise CinematicSkillFilmBuildError(
                    "shots must contain CinematicSkillShot values"
                )
            shot_by_id = {item.line_id: item for item in parsed}
            if len(shot_by_id) != len(parsed):
                raise CinematicSkillFilmBuildError("each narration line may have only one shot")
            unknown = set(shot_by_id) - set(narration_doc.lines)
            if unknown:
                raise CinematicSkillFilmBuildError(
                    f"shot plan references unknown narration line IDs: {sorted(unknown)}"
                )

        engine = self._engine()
        film = engine.Film(duration=narration_doc.duration, fps=fps, look=look)
        film.auto_cues = True
        film.auto_whoosh = True

        for index, line in enumerate(lines):
            shot = shot_by_id.get(line.line_id, CinematicSkillShot(
                line_id=line.line_id,
                kind="card",
                title=f"KEY IDEA {index + 1:02d}",
                body=(line.caption or line.spoken_text,),
            ))
            if shot.kind not in self.SUPPORTED_KINDS:
                raise CinematicSkillFilmBuildError(
                    f"unsupported visual kind {shot.kind!r}; "
                    f"choose one of {sorted(self.SUPPORTED_KINDS)}"
                )
            if shot.kind == "image" and not shot.image_path:
                raise CinematicSkillFilmBuildError("image shots require image_path")
            if shot.kind != "image" and shot.image_path is not None:
                raise CinematicSkillFilmBuildError("image_path is only valid for image shots")

            x = index * 3600.0
            y = 0.0
            film.shot(line.start_seconds, x, y, 1.0, radius=1750, strength=0.48)

            if shot.kind == "image":
                key, aspect = self._stage_image(narration_doc, shot.image_path)
                film.add(engine.Print(
                    key, x=x, y=y, w=2500,
                    t_in=line.start_seconds, t_out=line.end_seconds,
                    paper=False, pin=True, label=shot.title or None,
                    aspect=aspect,
                ))
            elif shot.kind == "card":
                body = shot.body or (line.caption or line.spoken_text,)
                wrapped = tuple(
                    part for paragraph in body
                    for part in self._wrap_lines(paragraph)
                )
                if len(wrapped) > 5:
                    raise CinematicSkillFilmBuildError(
                        f"shot for line {line.line_id} exceeds five body lines; "
                        "split its text into shorter narration-backed shots"
                    )
                film.add(engine.Card(
                    x=x, y=y, w=2920, h=1580,
                    t_in=line.start_seconds,
                    t_out=line.end_seconds,
                    title=shot.title or f"KEY IDEA {index + 1:02d}",
                    lines=wrapped,
                    accent=(112, 178, 182),
                    title_size=170,
                    body_size=132,
                ))
            elif shot.kind == "title":
                title = shot.title or line.caption or line.spoken_text
                film.add(engine.BigText(
                    text=title, x=x, y=y, size=190,
                    t_in=line.start_seconds, t_out=line.end_seconds,
                    font="cond", type_on=0.45, rules=True,
                ))
            else:
                if isinstance(shot.counter_value, bool) or not isinstance(shot.counter_value, int):
                    raise CinematicSkillFilmBuildError(
                        f"counter shot for line {line.line_id} requires an integer counter_value"
                    )
                film.add(engine.Counter(
                    x=x, y=y, size=260, value=shot.counter_value,
                    t_in=line.start_seconds, t_out=line.end_seconds,
                    dur=min(1.3, max(0.35, line.end_seconds - line.start_seconds)),
                    prefix=shot.counter_prefix, suffix=shot.counter_suffix,
                    caption=shot.counter_caption or shot.title,
                ))

            if shot.emphasis_word:
                word_time = narration_doc.W(line.line_id, shot.emphasis_word)
                if not line.start_seconds <= word_time < line.end_seconds:
                    raise CinematicSkillFilmBuildError(
                        f"measured emphasis cue for line {line.line_id} is outside its line"
                    )
                film.add(engine.BigText(
                    text=shot.emphasis_word, x=x, y=650, size=150,
                    t_in=word_time, t_out=line.end_seconds,
                    font="label", type_on=0.18, grunge=False,
                    bar=(222, 176, 52), bar_h=0.55,
                ))

        if not film.cam_keys:
            raise CinematicSkillFilmBuildError("no camera keys were generated")
        return film
